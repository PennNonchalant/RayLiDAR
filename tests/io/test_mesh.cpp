void SetU32(std::vector<std::uint8_t> &bytes, const std::size_t offset, const std::uint32_t value)
{
    bytes[offset] = static_cast<std::uint8_t>(value & 0xFFU);
    bytes[offset + 1] = static_cast<std::uint8_t>((value >> 8U) & 0xFFU);
    bytes[offset + 2] = static_cast<std::uint8_t>((value >> 16U) & 0xFFU);
    bytes[offset + 3] = static_cast<std::uint8_t>((value >> 24U) & 0xFFU);
}

void ExpectIoError(const std::function<void()> &call, const std::string &needle)
{
    try
    {
        call();
    }
    catch (const IoError &error)
    {
        CHECK(error.exitCode() == 4);
        INFO(error.what());
        CHECK(std::string(error.what()).find(needle) != std::string::npos);
        return;
    }
    FAIL("expected raylidar::IoError");
}

std::string PlyHeader(const std::string &format = "binary_little_endian",
                      const std::string &frameComment = "comment frame W",
                      const std::string &unitsComment = "comment units m",
                      const std::string &xProperty = "property double x",
                      const std::uint64_t vertexCount = 3U,
                      const std::uint64_t faceCount = 1U)
{
    std::string header = "ply\n";
    header += "format " + format + " 1.0\n";
    header += "comment generated by tests\n";
    if (!frameComment.empty())
    {
        header += frameComment + "\n";
    }
    if (!unitsComment.empty())
    {
        header += unitsComment + "\n";
    }
    header += "element vertex " + std::to_string(vertexCount) + "\n";
    header += xProperty + "\n";
    header += "property double y\n";
    header += "property double z\n";
    header += "element face " + std::to_string(faceCount) + "\n";
    header += "property list uchar int vertex_indices\n";
    header += "end_header\n";
    return header;
}

void AppendVertex(std::vector<std::uint8_t> &body, const double x, const double y,
                  const double z)
{
    AppendF64(body, x);
    AppendF64(body, y);
    AppendF64(body, z);
}

void AppendFace3(std::vector<std::uint8_t> &body, const std::uint32_t a, const std::uint32_t b,
                 const std::uint32_t c)
{
    body.push_back(3U);
    AppendU32(body, a);
    AppendU32(body, b);
    AppendU32(body, c);
}

std::vector<std::uint8_t> ValidPlyBody()
{
    std::vector<std::uint8_t> body;
    AppendVertex(body, 0.0, 0.0, 0.0);
    AppendVertex(body, 1.0, 0.0, 0.0);
    AppendVertex(body, 0.0, 1.0, 0.5);
    AppendFace3(body, 0U, 1U, 2U);
    return body;
}

json ValidGlbJson()
{
    return json::parse(R"JSON(
{
  "asset": {"version": "2.0", "extras": {"frame": "W", "units": "m"}},
  "scene": 0,
  "scenes": [{"nodes": [0]}],
  "nodes": [{"mesh": 0}],
  "meshes": [{"primitives": [{"attributes": {"POSITION": 0}, "indices": 1}]}],
  "accessors": [
    {"bufferView": 0, "componentType": 5126, "count": 3, "type": "VEC3",
     "min": [-1.0, -2.0, -3.0], "max": [1.0, 2.0, 3.0]},
    {"bufferView": 1, "componentType": 5123, "count": 3, "type": "SCALAR"}
  ],
  "bufferViews": [
    {"buffer": 0, "byteOffset": 0, "byteLength": 36},
    {"buffer": 0, "byteOffset": 36, "byteLength": 6}
  ],
  "buffers": [{"byteLength": 42}]
}
)JSON");
}

std::vector<std::uint8_t> ValidGlbBin()
{
    return std::vector<std::uint8_t>(42U, 0U);
}

void ExpectGlbRejected(const fs::path &root, const json &document, const std::string &needle)
{
    const std::vector<std::uint8_t> bin = ValidGlbBin();
    const std::vector<std::uint8_t> bytes = BuildGlb(document.dump(), bin);
    const fs::path path = WriteTempFile(root, "bad.glb", bytes);
    ExpectIoError([&path] { (void)ValidateMeshFile(path); }, needle);
}

std::string ValidObj()
{
    return "# frame W\n"
           "# units m\n"
           "v 0 0 0\n"
           "v 1 0 0\n"
           "v 0 1 0\n"
           "f 1 2 3\n";
}
